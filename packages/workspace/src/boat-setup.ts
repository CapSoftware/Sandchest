import { posix } from "node:path";
import { WorkspaceError } from "./index";

export interface AgentSandboxSetup {
  /** The unprivileged user the agent runs as, created by the script (it must not exist yet). Default `sandchest-agent`. */
  user?: string;
  /** The checkout the agent may read. Default `/home/user/repo` (`BoatWorkspace.root`). */
  checkoutDir?: string;
  /** The one directory the agent may write. Default `/home/user/agent` (`BoatWorkspace.agentDir`). */
  workDir?: string;
  /** Hosts the agent may reach on TCP 443, e.g. its model gateway. Resolved to addresses when the script runs. May be empty when `loopbackPorts` is not. */
  allowHosts: string[];
  /** Loopback TCP ports the agent may reach (a local tool server, say). Default none. */
  loopbackPorts?: number[];
  /** Let the agent query the configured resolvers. Default true; false leaves it no DNS at all. */
  dns?: boolean;
}

const USER = /^[a-z_][a-z0-9_-]{0,31}$/;
const RESERVED_USERS = new Set(["root", "user", "nobody", "daemon"]);
const LABEL = "[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?";
const HOST = new RegExp(`^(?=.{1,253}$)${LABEL}(?:\\.${LABEL})*$`);
const SAFE_PATH = /^\/[A-Za-z0-9._/-]+$/;

/**
 * Builds a Boat `setupScript` that prepares a sandbox for an agent that reads
 * untrusted input (the repository under scan):
 *
 * - creates `user`, a new system account in no groups, with no password and
 *   no login shell, then checks it cannot sudo (setup fails if it can);
 * - lets it read the checkout and write only `workDir`, which it owns with the
 *   sandbox user's group (setgid), so the sandbox user can read what it writes
 *   there; directories above them inside the sandbox user's home become
 *   traverse-only, and everything else already in that home loses "other"
 *   access;
 * - installs iptables and ip6tables rules, as root, that drop every packet
 *   that user sends except TCP 443 to the addresses `allowHosts` resolve to,
 *   DNS to the resolvers in /etc/resolv.conf (unless `dns` is false), and
 *   `loopbackPorts`.
 *
 * The script runs as Boat's sandbox user (passwordless sudo) under `set -eu`;
 * any failure (no iptables, a host that does not resolve, an agent that can
 * sudo) fails setup, and `BoatWorkspace.create` then fails and deletes the
 * sandbox. Run the agent with `spawn(cmd, { runAs: user })`.
 *
 * Limits, honestly:
 * - Addresses are resolved once, at setup. A host whose addresses change later
 *   becomes unreachable; one behind a shared CDN address makes every other
 *   site on that address reachable too (TLS SNI is not checked).
 * - DNS is allowed to the configured resolvers, which forward anywhere, so a
 *   determined agent can still leak data through DNS queries. `dns: false`
 *   closes that, for an agent that reaches only `loopbackPorts`.
 * - Only this user's traffic is filtered. Processes started by the sandbox
 *   user (clone, indexer, setup) are not, and the agent can still talk to them
 *   over `loopbackPorts`.
 * - The checkout must be world-readable (git's default umask 022 does this),
 *   and world-readable files the sandbox user creates later at paths the agent
 *   can guess stay readable. The agent can list processes, but not read other
 *   users' environments.
 * - It is a privilege boundary inside one VM, not a VM boundary: a kernel or
 *   setuid exploit gets past it. Keep secrets out of the sandbox (`noEnv`).
 */
export function agentSandboxSetupScript(setup: AgentSandboxSetup): string {
  const user = setup.user ?? "sandchest-agent";
  if (!USER.test(user) || RESERVED_USERS.has(user)) throw new WorkspaceError(`Invalid agent user name: ${user.slice(0, 32)}`);
  const checkoutDir = checkPath(setup.checkoutDir ?? "/home/user/repo", "checkoutDir");
  const workDir = checkPath(setup.workDir ?? "/home/user/agent", "workDir");
  if (isWithin(workDir, checkoutDir) || isWithin(checkoutDir, workDir)) throw new WorkspaceError("checkoutDir and workDir must not contain each other");
  const ports = setup.loopbackPorts ?? [];
  if (setup.allowHosts.length === 0 && ports.length === 0) throw new WorkspaceError("allowHosts and loopbackPorts are both empty: the agent could reach nothing but DNS");
  for (const host of setup.allowHosts) if (!HOST.test(host)) throw new WorkspaceError(`Invalid host: ${host.slice(0, 253)}`);
  for (const port of ports) if (!Number.isInteger(port) || port < 1 || port > 65_535) throw new WorkspaceError(`Invalid port: ${port}`);

  const ancestors = [...new Set([...parents(checkoutDir), ...parents(workDir)])];

  return `set -eu
# Generated by agentSandboxSetupScript. Runs once as the sandbox user, with passwordless sudo.
AGENT='${user}'
CHECKOUT='${checkoutDir}'
WORKDIR='${workDir}'
ALLOW_HOSTS='${setup.allowHosts.join(" ")}'
LOOPBACK_PORTS='${ports.join(" ")}'
DNS='${setup.dns === false ? "no" : "yes"}'
CHAIN=SANDCHEST_AGENT
SANDBOX_USER="$(id -un)"
SANDBOX_GROUP="$(id -gn)"
fail() { echo "agent setup: $*" >&2; exit 1; }
[ "$AGENT" != "$SANDBOX_USER" ] || fail "the agent user must not be the sandbox user"

# 1. A new unprivileged user, in no groups: no password, no login shell, no sudo.
! id -u "$AGENT" >/dev/null 2>&1 || fail "user $AGENT already exists"
sudo -n useradd --system --no-create-home --home-dir "$WORKDIR" --shell /usr/sbin/nologin "$AGENT"
AGENT_UID="$(id -u "$AGENT")"
[ "$AGENT_UID" -ne 0 ] || fail "the agent user is root"
if sudo -n -u "$AGENT" -- sudo -n true >/dev/null 2>&1; then fail "the agent user can use sudo"; fi

# 2. Files: nothing in the sandbox user's home for others, then read the checkout, write the work directory.
sudo -n find "$HOME" -mindepth 1 -maxdepth 1 ! -type l ! -path "$CHECKOUT" ! -path "$WORKDIR" -exec chmod o-rwx {} +
mkdir -p "$CHECKOUT"
chmod 755 "$CHECKOUT"
sudo -n mkdir -p "$WORKDIR"
sudo -n chown "$AGENT:$SANDBOX_GROUP" "$WORKDIR"
sudo -n chmod 2770 "$WORKDIR"
# Directories above them: traverse only inside the sandbox user's home (no listing), traverse elsewhere.
traverse() {
  case "$1" in
    "$HOME" | "$HOME"/*) sudo -n chmod o-rw,o+x "$1" ;;
    *) sudo -n chmod o+x "$1" ;;
  esac
}
${ancestors.map((dir) => `traverse '${dir}'`).join("\n")}

# 3. Network: the agent's packets go to one chain that accepts the allowed destinations and drops the rest.
command -v iptables >/dev/null 2>&1 || fail "iptables is not installed"
V4=""
V6=""
for host in $ALLOW_HOSTS; do
  a="$(getent ahostsv4 "$host" | awk '{ print $1 }' | sort -u || true)"
  b="$(getent ahostsv6 "$host" | awk '{ print $1 }' | grep ':' | grep -v '^::ffff:' | sort -u || true)"
  [ -n "$a$b" ] || fail "cannot resolve $host"
  V4="$V4 $a"
  V6="$V6 $b"
done
NS4=""
NS6=""
if [ "$DNS" = yes ]; then
  for ns in $(awk '$1 == "nameserver" { sub(/%.*/, "", $2); print $2 }' /etc/resolv.conf); do
    case "$ns" in *:*) NS6="$NS6 $ns" ;; *) NS4="$NS4 $ns" ;; esac
  done
fi

firewall() {
  t="$1"; addresses="$2"; resolvers="$3"
  sudo -n "$t" -w -N "$CHAIN" 2>/dev/null || sudo -n "$t" -w -F "$CHAIN"
  sudo -n "$t" -w -C OUTPUT -m owner --uid-owner "$AGENT_UID" -j "$CHAIN" 2>/dev/null \\
    || sudo -n "$t" -w -I OUTPUT 1 -m owner --uid-owner "$AGENT_UID" -j "$CHAIN"
  for ns in $resolvers; do
    sudo -n "$t" -w -A "$CHAIN" -p udp -d "$ns" --dport 53 -j ACCEPT
    sudo -n "$t" -w -A "$CHAIN" -p tcp -d "$ns" --dport 53 -j ACCEPT
  done
  for port in $LOOPBACK_PORTS; do
    sudo -n "$t" -w -A "$CHAIN" -o lo -p tcp --dport "$port" -j ACCEPT
  done
  for ip in $addresses; do
    sudo -n "$t" -w -A "$CHAIN" -p tcp -d "$ip" --dport 443 -j ACCEPT
  done
  sudo -n "$t" -w -A "$CHAIN" -j DROP
}

firewall iptables "$V4" "$NS4"
if command -v ip6tables >/dev/null 2>&1; then
  firewall ip6tables "$V6" "$NS6"
elif [ -e /proc/net/if_inet6 ]; then
  fail "IPv6 is enabled but ip6tables is not installed"
fi
echo "agent setup: done"
`;
}

function checkPath(path: string, name: string): string {
  if (!SAFE_PATH.test(path) || posix.normalize(path) !== path || path.endsWith("/") || path.split("/").length < 3) {
    throw new WorkspaceError(`${name} must be an absolute, normalised path at least two levels deep: ${path.slice(0, 200)}`);
  }
  return path;
}

function isWithin(path: string, dir: string): boolean {
  return path === dir || path.startsWith(`${dir}/`);
}

/** `/home/user/repo` → `/home`, `/home/user`. */
function parents(path: string): string[] {
  const parts = path.split("/").slice(1, -1);
  return parts.map((_, i) => `/${parts.slice(0, i + 1).join("/")}`);
}
